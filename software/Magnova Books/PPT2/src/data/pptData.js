function createClass2VyakranSlides(chapter) {
  const slides = [
    {
      type: "title",
      title: chapter.chapterName,
      subtitle: chapter.subtitle,
      subject: "Hindi Vyakaran",
      publication: "Vyakaran 2"
    },
    {
      type: "beforeYouRead",
      title: "आओ जानें",
      points: chapter.concepts.map(
        (concept) => concept.title
      )
    },
    {
      type: "introduction",
      title: "आइए समझें",
      content: chapter.concepts[0].points.join(" ")
    },
    ...chapter.concepts.map((concept) => ({
      type: "concept",
      title: concept.title,
      points: concept.points
    })),
    {
      type: "activity",
      title: "देखो, पढ़ो और समझो",
      points: chapter.activity
    },
    {
      type: "questions",
      title: "आओ, बताओ",
      questions: chapter.questions
    },
    {
      type: "lessonForLife",
      title: "अच्छी बातें",
      points: chapter.life
    },
    {
      type: "thankYou",
      title: "धन्यवाद!",
      subtitle: "सीखते रहें, आगे बढ़ते रहें।"
    }
  ];

  return slides.map((slide, index) => ({
    slideNumber: index + 1,
    ...slide
  }));
}

