// ---------- NEW SLIDE STRUCTURE (10 slides) ----------
export const SLIDE_COUNT = 10;

export function buildSlides(c) {
  const letters = ["A", "B", "C"];
  return [
    {
      kind: "cover",
      title: c.title,
      tag: `Chapter ${c.id} • ${c.subject}`,
      lines: [c.topic],
    },
    {
      kind: "goals",
      title: "Today we will learn",
      tag: "Goals",
      lines: [
        `Understand: ${c.topic.toLowerCase()}`,
        `Use the words ${c.words.join(", ")}`,
        "Solve a puzzle and a quick quiz",
      ],
    },
    {
      kind: "warmup",
      title: "Warm-up",
      tag: "Think first",
      lines: [
        `Where do you see "${c.words[0].toLowerCase()}" in daily life?`,
        "Talk to your partner for one minute.",
      ],
    },
    { kind: "words", title: "Magic words", tag: "Vocabulary", lines: c.words },
    {
      kind: "concept",
      title: c.topic,
      tag: "Big idea",
      lines: [
        `Key word: ${c.words[0]}`,
        `Key word: ${c.words[1]}`,
        `Remember: ${c.words[2]}`,
      ],
    },
    {
      kind: "example",
      title: "Watch me solve it",
      tag: "Example",
      lines: [c.eq, `Answer: ${c.ea}`],
    },
    {
      kind: "practice",
      title: "Solve it together",
      tag: "Guided practice",
      lines: [`Try a similar one: ${c.eq}`, "Show your steps on the board."],
    },
    {
      kind: "quiz",
      title: c.qq,
      tag: "Quick quiz",
      lines: c.opts.map((o, i) => `${letters[i]}. ${o}`),
      answer: c.ans,
    },
    {
      kind: "recap",
      title: "Let's recap",
      tag: "Remember",
      lines: [`${c.topic}`, `Words: ${c.words.join(" • ")}`],
    },
    {
      kind: "home",
      title: "Home challenge",
      tag: "Homework",
      lines: [
        "Find 3 real examples at home.",
        "Draw one and bring it to class.",
      ],
    },
  ];
}
