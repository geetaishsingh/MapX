// Default to the creative Electric Violet & Indigo theme
export const DEFAULT_THEME = THEMES[0];

// Legacy ID mapping for backwards compatibility
const LEGACY_MAP = {
  indigo: "studio-violet",
  emerald: "aurora-emerald",
  ocean: "electric-azure",
  purple: "cosmic-purple",
  crimson: "sunset-coral",
  amber: "cyber-amber",
  teal: "teal-breeze",
  slate: "obsidian-luxe",
  coral: "sunset-coral",
  fuchsia: "berry-fuchsia",
};

export const getThemeById = (id) => {
  if (!id) return DEFAULT_THEME;
  const direct = THEMES.find((t) => t.id === id);
  if (direct) return direct;
  const legacyId = LEGACY_MAP[id];
  if (legacyId) {
    return THEMES.find((t) => t.id === legacyId) || DEFAULT_THEME;
  }
  return DEFAULT_THEME;
};
